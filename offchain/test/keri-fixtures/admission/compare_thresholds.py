#!/usr/bin/env python3
"""Join thresholds.json (keripy), lean-thresholds.jsonl (Lean `Threshold.satisfied`) and aiken-thresholds.txt
(the codec's pass/fail list) into THRESHOLDS.md and thresholds-comparison.json."""
import json, os, re

out = os.environ.get("ADMISSION_OUT") or os.getcwd()
data = json.load(open(os.path.join(out, "thresholds.json")))
lean = {}
for line in open(os.path.join(out, "lean-thresholds.jsonl")):
    r = json.loads(line)
    lean[r["id"]] = r
aiken = {}
for line in open(os.path.join(out, "aiken-thresholds.txt")):
    line = re.sub(r"\x1b\[[0-9;]*[a-zA-Z]", "", line)
    m = re.search(r"(PASS|FAIL)\s+\[[^\]]*\]\s+(?:\S+\.)?(wf_\w+|ev_\w+)", line)
    if m:
        aiken[m.group(2)] = m.group(1) == "PASS"

rows, md = [], ["# Stage B: signing thresholds, generated by compare_thresholds.py (do not edit)\n",
                "| case | threshold (wire) | keys | keripy 1.3.5 | Lean `Threshold.satisfied` | Aiken codec (`well_formed`, `evaluate`) | direction |",
                "|---|---|---|---|---|---|---|"]
for c in data["cases"]:
    k = c["keripy"]
    kadmits = k["constructed"] and k.get("appliesToKeyCount", False) and any(k["satisfied"].values())  # constructible, fits the keys, and some set of signers satisfies it
    rep = "count" in c["threshold"] or ("weighted" in c["threshold"] and all("key" in w for cl in c["threshold"]["weighted"] for w in cl))
    wf = aiken.get("wf_" + c["id"])
    if rep and wf is None:
        raise SystemExit("thresholds: no Aiken well-formedness result for " + c["id"])
    if k["constructed"]:
        kdesc = ("admits (%s)" % ("weighted" if k["weighted"] else "count")) if kadmits else ("refuses: does not fit %d keys" % c["n"] if not k.get("appliesToKeyCount", False) else "constructs but no set of signers satisfies it (pending forever)")
    else:
        kdesc = "refuses: " + k["error"][:60]
    L = lean[c["id"]].get("satisfied") if c["id"] in lean else None
    subsets = list(k["satisfied"].keys()) if k["constructed"] else [("".join(str(i) for i in range(c["n"])))]
    diffs_lean, diffs_aiken = [], []
    if kadmits:
        for s in k["satisfied"]:
            if L is not None and L[s] != k["satisfied"][s]:
                diffs_lean.append("%s: keripy %s, Lean %s" % (s or "none", k["satisfied"][s], L[s]))
            if rep and wf and aiken.get("ev_%s_%s" % (c["id"], s or "none")) != k["satisfied"][s]:
                diffs_aiken.append("%s: keripy %s, Aiken %s" % (s or "none", k["satisfied"][s], aiken.get("ev_%s_%s" % (c["id"], s or "none"))))
    ldesc = "no row" if L is None else ("evaluates; all %d subsets as keripy" % len(L) if kadmits and not diffs_lean else
                                        ("differs on " + "; ".join(diffs_lean[:3]) if kadmits else
                                         "evaluates a threshold keripy refuses: satisfied by %d of %d subsets" % (sum(L.values()), len(L))))
    if not rep:
        adesc = "not representable in the codec's types"
    elif not wf:
        adesc = "well_formed refuses"
    else:
        adesc = "well formed; " + ("evaluate as keripy on all subsets" if kadmits and not diffs_aiken else ("evaluate differs on " + "; ".join(diffs_aiken[:3]) if kadmits else "evaluate answers"))
    if kadmits:
        direction = []
        if diffs_lean:
            direction.append("model differs")
        if not rep:
            direction.append("chain cannot hold what keripy admits")
        elif not wf:
            direction.append("WE-REFUSE (codec refuses what keripy admits)")
        elif diffs_aiken:
            direction.append("codec differs")
        direction = "; ".join(direction) or "agree"
    else:
        direction = []
        if L is not None and any(L.values()):
            direction.append("WE-ACCEPT in the model (satisfiable on %d subsets)" % sum(L.values()))
        if rep and wf:
            direction.append("WE-ACCEPT in the codec (well formed)")
        direction = "; ".join(direction) or "agree"
    rows.append({"id": c["id"], "sith": c["sith"], "n": c["n"], "keripy": kdesc, "lean": ldesc, "aiken": adesc, "direction": direction})
    md.append("| %s | `%s` | %d | %s | %s | %s | %s |" % (c["id"], json.dumps(c["sith"]), c["n"], kdesc, ldesc, adesc, direction))
json.dump(rows, open(os.path.join(out, "thresholds-comparison.json"), "w"), indent=1)
open(os.path.join(out, "THRESHOLDS.md"), "w").write("\n".join(md) + "\n")
for r in rows:
    print(r["id"], "|", r["direction"])
