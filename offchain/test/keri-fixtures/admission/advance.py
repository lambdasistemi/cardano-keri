#!/usr/bin/env python3
"""Stage C on the chain: the rotation corpus through the Aiken advance predicate.

For every rotation step of the corpus whose predecessor is an accepted inception, `gen` writes an Aiken test that
builds what an honest prover supplies: the spent checkpoint (the inception's state), the created datum derived from
the rotation (keys, thresholds, derived witnesses, toad, sequence), and the evidence (event bytes, offsets from
gen_fixtures._offsets_record, cut and add lists, controller signatures, witness receipts), and asks
`advance_predicate`. Each test prints the verdict and fails on purpose; `compare` joins the traces with keripy.
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import keripy_admission as K  # noqa: E402
import gen_fixtures as G  # noqa: E402
import registration as R  # noqa: E402  (th, raw_of, hexof)
from keri.core import serdering  # noqa: E402

out = os.environ.get("ADMISSION_OUT") or os.getcwd()
MSG = ["Eq2AssetOrAidMismatch", "Eq5SequenceMismatch", "EqW1CutInvalid", "EqW2AddInvalid", "Eq6CurrentQuorumUnsatisfied",
       "Eq6PriorNextQuorumUnsatisfied", "Eq7CreatedStateMismatch"]
EVT = ["AE1EventTypeMismatch", "AE2AidMismatch", "AE3SequenceMismatch", "AE4CurKeysMismatch", "AE5CurThresholdMismatch", "AE6NextKeysMismatch",
       "AE7NextThresholdMismatch", "AE8WitCutMismatch", "AE9WitAddMismatch", "AE10ToadMismatch"]


def rows():
    """(case, step, role) for each rotation step with an accepted inception as predecessor."""
    for c in K.CASES:
        steps = c["build"]()
        icp = [s for s in steps if s["role"] == "context" and K.sad_of(s["raw"])["t"] == "icp"]
        if len(icp) != 1 or [s for s in steps if s["role"] == "context" and K.sad_of(s["raw"])["t"] == "rot"]:
            continue
        for st in steps:
            if st["role"] == "subject" and K.sad_of(st["raw"])["t"] == "rot":
                yield c, st, K.sad_of(icp[0]["raw"])


def lst(items):
    return "[" + ", ".join(items) + "]"


def gen(dest):
    keripy = {r["id"]: r for r in json.load(open(os.path.join(out, "keripy-results.json")))["cases"]}
    names = "".join("        %s -> @\"%s\"\n" % (e, e) for e in MSG)
    evs = "".join("        %s -> @\"%s\"\n" % (e, e) for e in EVT)
    lines = ["//// the rotation corpus through advance_predicate (generated by advance.py; do not edit).",
             "//// Every test prints its verdict and fails on purpose: the traces are the measurement.", "",
             "use cardano_keri/checkpoint/advance.{AdvanceEvidence, AdvancePredicateInvalid, AdvancePredicateValid, AdvancePredicateVerdict, AdvMessageInvalid, AdvEventBinding, AdvReceiptQuorumUnsatisfied, advance_predicate, " + ", ".join(EVT) + "}",
             "use cardano_keri/checkpoint/datum.{KeyStateView}",
             "use cardano_keri/checkpoint/message.{SpentCheckpoint, deriveAidAssetName, " + ", ".join(MSG) + ", Eq8CreatedIllFormed}",
             "use cardano_keri/checkpoint/threshold.{Unweighted, Weight, Weighted}", "",
             "fn name(v: AdvancePredicateVerdict) -> String {\n  when v is {\n    AdvancePredicateValid -> @\"Valid\"\n    AdvReceiptQuorumUnsatisfiedPlaceholder\n  }\n}\n"]
    lines[-1] = ("fn name(v: AdvancePredicateVerdict) -> String {\n  when v is {\n    AdvancePredicateValid -> @\"Valid\"\n    AdvancePredicateInvalid(e) ->\n      when e is {\n"
                 "        AdvReceiptQuorumUnsatisfied -> @\"AdvReceiptQuorumUnsatisfied\"\n        AdvMessageInvalid(m) ->\n          when m is {\n" +
                 "".join("            %s -> @\"%s\"\n" % (e, e) for e in MSG) + "            Eq8CreatedIllFormed(_) -> @\"Eq8CreatedIllFormed\"\n          }\n"
                 "        AdvEventBinding(b) ->\n          when b is {\n" + "".join("            %s -> @\"%s\"\n" % (e, e) for e in EVT) + "          }\n      }\n  }\n}\n")
    notes = []
    for c, st, icp in rows():
        sad = K.sad_of(st["raw"])
        tag = c["id"]
        if keripy[c["id"]]["steps"][-1]["outcome"] == "refused-at-parse" and st["role"] == "subject":
            notes.append({"id": tag, "reason": "keripy refuses the bytes at parse: no evidence an honest prover can build"})
            continue
        if st["raw"][:1] != b"{":
            notes.append({"id": tag, "reason": "the event is serialized as CBOR; the harness builds offsets into JSON bytes only (a coverage gap of the harness)"})
            continue
        cur_t, nxt_t = R.th(K.threshold_json(sad["kt"])), R.th(K.threshold_json(sad["nt"]))
        s_nt = R.th(K.threshold_json(icp["nt"]))
        if cur_t is None or nxt_t is None or s_nt is None:
            notes.append({"id": tag, "reason": "a nested weight group has no representation in the datum's Threshold type"})
            continue
        cut, add = sad.get("br", []), sad.get("ba", [])
        spent_w = icp.get("b", [])
        derived = [w for w in spent_w if w not in cut] + list(add)
        serder = serdering.SerderKERI(raw=st["raw"])
        off = G._offsets_record(serder, rotation_fields=True)
        sigs = [(t[1], K.sign_with(t, serder.raw).raw) for t in st["sig_by"]]
        wits = [(t[1], K.sign_with(t, serder.raw).raw) for t in st["wit_by"]]
        aid = R.hexof(R.raw_of(icp["i"]))
        lines.append(
            "test adv_%s() {\n  let spent = SpentCheckpoint {\n    network_id: 0,\n    policy_id: #\"00\",\n    aid_asset_name: deriveAidAssetName(%s),\n    txid: #\"00\",\n    index: 0,\n    cesr_aid: %s,\n"
            "    witnesses: %s,\n    next_keys: %s,\n    next_threshold: %s,\n    seq: 0,\n    native_sn: 0,\n  }\n"
            % (tag, aid, aid, lst([R.hexof(R.raw_of(w)) for w in spent_w]), lst([R.hexof(R.raw_of(k)) for k in icp["n"]]), s_nt))
        lines.append(
            "  let new = KeyStateView {\n    cesr_aid: %s,\n    cur_keys: %s,\n    cur_threshold: %s,\n    next_keys: %s,\n    next_threshold: %s,\n    witnesses: %s,\n    toad: %d,\n    seq: 1,\n    native_sn: %d,\n  }\n"
            % (aid, lst([R.hexof(R.raw_of(k)) for k in sad["k"]]), cur_t, lst([R.hexof(R.raw_of(k)) for k in sad["n"]]), nxt_t,
               lst([R.hexof(R.raw_of(w)) for w in derived]), int(sad["bt"], 16), int(sad["s"], 16)))
        lines.append(
            "  let e = AdvanceEvidence {\n    event_bytes: %s,\n    off_t: %d,\n    off_i: %d,\n    off_s: %d,\n    off_k: %s,\n    off_kt: %d,\n    off_n: %s,\n    off_nt: %d,\n    off_br: %s,\n    off_ba: %s,\n    off_bt: %d,\n    wit_cut: %s,\n    wit_add: %s,\n    ctrl_sigs: %s,\n    wit_receipts: %s,\n  }\n"
            % (R.hexof(serder.raw), off["t"], off["i"], off["s"], off["k"], off["kt"], off["n"], off["nt"], off["br"], off["ba"], off["bt"],
               lst([R.hexof(R.raw_of(w)) for w in cut]), lst([R.hexof(R.raw_of(w)) for w in add]),
               lst(["(%d, %s)" % (x, R.hexof(s)) for x, s in sigs]), lst(["(%d, %s)" % (x, R.hexof(s)) for x, s in wits])))
        lines.append("  let v = advance_predicate(spent, new, e)\n  trace name(v)\n  False\n}\n")
    open(dest, "w").write("\n".join(lines) + "\n")
    json.dump(notes, open(os.path.join(out, "advance-not-built.json"), "w"), indent=1)
    print("wrote %s: %d tests, %d without evidence" % (dest, sum(1 for l in lines if l.startswith("test ")), len(notes)))


def compare(aiken_txt):
    keripy = {r["id"]: r for r in json.load(open(os.path.join(out, "keripy-results.json")))["cases"]}
    verdict, cur = {}, None
    for line in open(aiken_txt):
        line = re.sub(r"\x1b\[[0-9;]*[a-zA-Z]", "", line)
        m = re.search(r"(?:PASS|FAIL)\s+\[[^\]]*\]\s+(?:\S+\.)?adv_(\w+)", line)
        if m:
            cur = m.group(1)
            continue
        t = re.match(r"\s*│\s*\|\s*(\w+)\s*$", line)
        if cur and t:
            verdict.setdefault(cur, t.group(1))
    notes = {n["id"]: n["reason"] for n in json.load(open(os.path.join(out, "advance-not-built.json")))}
    table = []
    for c, st, icp in rows():
        tag = c["id"]
        k = keripy[c["id"]]["steps"][-1]
        kc = {"accepted": "accepted", "escrowed": "pending", "refused": "refused", "refused-at-parse": "refused at parse", "unknown": "unknown"}[k["outcome"]]
        if tag in notes:
            table.append({"case": tag, "title": c["title"], "keripy": kc, "keripyClass": k["class"], "chain": "no evidence built", "direction": "not comparable: " + notes[tag]})
            continue
        if tag not in verdict:
            raise SystemExit("advance: no named verdict for " + tag)
        v = verdict[tag]
        valid = v == "Valid"
        d = "agree" if (k["outcome"] == "accepted") == valid else ("WE-REFUSE" if k["outcome"] == "accepted" else "WE-ACCEPT")
        if d == "agree" and k["outcome"] == "escrowed":
            d = "agree, keripy pends"
        table.append({"case": tag, "title": c["title"], "keripy": kc, "keripyClass": k["class"], "chain": v, "direction": d})
    json.dump(table, open(os.path.join(out, "advance-comparison.json"), "w"), indent=1)
    md = ["# Stage C on the chain: rotations through `advance_predicate` (generated; do not edit)\n",
          "| case | what it tests | keripy 1.3.5 | advance predicate | direction |", "|---|---|---|---|---|"]
    for r in table:
        md.append("| %s | %s | %s | %s | %s |" % (r["case"], r["title"], r["keripy"] + (": " + r["keripyClass"] if r["keripyClass"] else ""), r["chain"], r["direction"]))
    open(os.path.join(out, "ADVANCE.md"), "w").write("\n".join(md) + "\n")
    for r in table:
        print(r["case"], "|", r["keripy"], r["keripyClass"][:22], "|", r["chain"], "|", r["direction"][:40])


if __name__ == "__main__":
    gen(sys.argv[2]) if sys.argv[1] == "gen" else compare(sys.argv[2])
