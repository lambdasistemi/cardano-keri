#!/usr/bin/env node
// The grammar rows of INV-BIND: the ten structural cases of the event object and its anchor
// array, as exact bytes shared by the Aiken reader and the Haskell reader.
//
//   node scripts/inv-bind-grammar-rows.mjs            # write
//   node scripts/inv-bind-grammar-rows.mjs --check    # exit 1 when it drifts
//
// Base: the committed key-derived-free 2-key inception of \`reg_2key\` (offchain/test/keri-fixtures/fixtures/registration.json),
// whose bytes are also the Aiken vector \`pos_2key_evidence\`. Every single-error JSON row has its declared length
// fixed up so that the intended grammar check is the one exercised, except the size-mismatch row.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const fixtures = join(root, 'offchain/test/keri-fixtures/fixtures');
const registration = JSON.parse(readFileSync(join(fixtures, 'registration.json'), 'utf8'));
const baseHex = registration.reg_2key.event.raw_hex;
const vectors = readFileSync(join(root, 'onchain/lib/cardano_keri/checkpoint/registration_vectors.ak'), 'utf8');
if (!vectors.includes(baseHex)) throw new Error('the base of the rows is not the Aiken vector pos_2key');
const base = Buffer.from(baseHex, 'hex').toString('utf8');
if (!base.endsWith('"a":[]}')) throw new Error('the base does not end with an empty anchor');

const sized = (text, size = Buffer.byteLength(text)) =>
  text.replace(/KERI10JSON[0-9a-f]{6}_/, 'KERI10JSON' + size.toString(16).padStart(6, '0') + '_');
const withAnchor = (anchor) => sized(base.replace('"a":[]}', '"a":' + anchor + '}'));
const seal = '{"i":"EAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA","s":"1","d":"EBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB"}';

// [row of the grammar table, variant id, expected, bytes]
const rows = [
  ['OBJ-1', 'OBJ-1', 'accept', base],
  ['OBJ-2', 'OBJ-2', 'refuse', sized(base.replace('"a":[]}', '"a":[],}'))],
  ['OBJ-3', 'OBJ-3', 'refuse', sized(base + '{}', Buffer.byteLength(base) + 2)],
  ['OBJ-4', 'OBJ-4', 'refuse', sized(base, Buffer.byteLength(base) - 1)],
  ['ANCH-1', 'ANCH-1', 'accept', base],
  ['ANCH-2', 'ANCH-2', 'accept', withAnchor('[' + seal + ']')],
  ['ANCH-3', 'ANCH-3', 'refuse', withAnchor('"[]"')],
  ['ANCH-4', 'ANCH-4a', 'refuse', withAnchor('0')],
  ['ANCH-4', 'ANCH-4b', 'refuse', withAnchor('{}')],
  ['ANCH-5', 'ANCH-5a', 'refuse', withAnchor('[' + seal + ',]')],
  ['ANCH-5', 'ANCH-5b', 'refuse', withAnchor('[' + seal + ',,' + seal + ']')],
  ['ANCH-6', 'ANCH-6a', 'refuse', withAnchor('[{"i":}]')],
  ['ANCH-6', 'ANCH-6b', 'refuse', withAnchor('[{"i":"EAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA"]')],
];

const hexOf = (text) => Buffer.from(text, 'utf8').toString('hex');
const json = JSON.stringify({ base_hex: baseHex, rows: rows.map(([row, variant, expected, text]) => ({ row, variant, expected, hex: hexOf(text) })) }, null, 1) + '\n';

const name = (variant) => variant.toLowerCase().replace('-', '_');
const constant = (n, hex) => {
  const head = `const ${n}: ByteArray =`;
  return `${head}\n  #"${hex}"\n`;
};
const tests = rows.map(([row, variant, expected, text]) => {
  const n = name(variant);
  const check = expected === 'accept' ? `row_binds(${n}_body)` : `!row_binds(${n}_body)`;
  return `test grammar_${n}_${expected}s() {\n  ${check}\n}\n`;
});
const ak = [
  '//// INV-BIND: the grammar rows of the event object and of its anchor array, on exact bytes shared with',
  '//// the Haskell reader (`inv_bind_grammar.json`). Generated by scripts/inv-bind-grammar-rows.mjs: do not edit. Every',
  '//// single-error JSON row has its declared length fixed up, except the size-mismatch row. An accept row is bound by',
  '//// the registration binder, a refuse row is not.',
  '',
  'use cardano_keri/checkpoint/registration.{\n  RegistrationEvidence, RegistrationValid, event_binding,\n}',
  'use cardano_keri/checkpoint/registration_vectors as vec',
  'use cardano_keri/checkpoint/spelling_fixture',
  '',
  ...rows.map(([row, variant, expected, text]) => constant(name(variant) + '_body', hexOf(text))),
  'fn row_binds(bytes: ByteArray) -> Bool {',
  '  event_binding(',
  '    vec.pos_2key_datum,',
  '    spelling_fixture.of_view(vec.pos_2key_datum),',
  '    RegistrationEvidence { ..vec.pos_2key_evidence, event_bytes: bytes },',
  '  ) == RegistrationValid',
  '}',
  '',
  ...tests,
].join('\n');

const jsonTarget = join(fixtures, 'inv_bind_grammar.json');
const akTarget = join(root, 'onchain/lib/cardano_keri/checkpoint/inv_bind_grammar_tests.ak');
if (process.argv.includes('--check')) {
  if (readFileSync(jsonTarget, 'utf8') !== json || readFileSync(akTarget, 'utf8') !== ak) {
    console.error('the grammar rows drift from their generator');
    process.exit(1);
  }
  console.log('the grammar rows match their generator');
} else {
  writeFileSync(jsonTarget, json);
  writeFileSync(akTarget, ak);
  console.log('wrote ' + jsonTarget + ' and ' + akTarget);
}
