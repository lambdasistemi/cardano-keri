{- |
Module      : Main
Description : Haskell-to-Aiken wire parity vectors for the one-step freeze (#345)

Generates the committed freeze wire constants from the Haskell encoders in
"Cardano.KERI.AID.Checkpoint.Wire". The Aiken module carries both the typed
inputs (a freeze evidence, a spent output reference, a policy, a hunter output
index) and the CBOR bytes the Haskell encoders produce for them; the Aiken
suite serialises its own typed value and compares, so a field order, a
constructor index or a tuple shape that disagrees between the layers fails.

Invocation: @gen-freeze-vectors [OUT_PATH]@.  The emitted module is
generated-only and checked for drift by @just check-freeze-vectors@.
-}
module Main (main) where

import Cardano.KERI.AID.Checkpoint.Advance (AdvanceEvidence (..))
import Cardano.KERI.AID.Checkpoint.Datum (KeyMaterial (..), canonicalCbor)
import Cardano.KERI.AID.Checkpoint.Freeze (FreezeEvidence (..))
import Cardano.KERI.AID.Checkpoint.Threshold (Threshold (..))
import Cardano.KERI.AID.Checkpoint.Wire (
    freezeEvidenceData,
    freezeObserverRedeemerData,
    freezeSpendRedeemerData,
 )
import Data.ByteArray.Encoding (Base (Base16), convertToBase)
import Data.ByteString (ByteString)
import Data.ByteString qualified as BS
import Data.ByteString.Char8 qualified as BC
import PlutusCore.Data (Data)
import PlutusTx.Builtins.Internal (BuiltinData (..))
import System.Environment (getArgs)

main :: IO ()
main = do
    args <- getArgs
    case args of
        [] -> putStr output
        [path] -> writeFile path output
        _ -> error "usage: gen-freeze-vectors [OUT_PATH]"

policy, spentTxId :: ByteString
policy = BS.replicate 28 0xc0
spentTxId = BS.replicate 32 0xe0

spentIndex, hunterIndex :: Integer
spentIndex = 7
hunterIndex = 5

-- | A small freeze evidence: every field distinct, so a transposition shows.
evidence :: FreezeEvidence
evidence =
    FreezeEvidence
        { feRotatedKeys =
            KeyMaterial
                { kmCurKeys = [BS.replicate 32 0x01]
                , kmCurThreshold = Unweighted 1
                , kmNextKeys = [BS.replicate 32 0x02]
                , kmNextThreshold = Unweighted 1
                , kmWitnesses = [BS.replicate 32 0x03]
                , kmToad = 1
                }
        , feRotatedSn = 6
        , feRotation =
            AdvanceEvidence
                { aeEventBytes = "rot"
                , aeOffT = 1
                , aeOffI = 2
                , aeOffS = 3
                , aeOffK = [4]
                , aeOffKt = 5
                , aeOffN = [6]
                , aeOffNt = 7
                , aeOffBr = [8]
                , aeOffBa = [9]
                , aeOffBt = 10
                , aeWitCut = ["cut"]
                , aeWitAdd = ["add"]
                , aeCtrlSigs = [(0, BS.replicate 64 0xc1)]
                , aeWitReceipts = [(1, BS.replicate 64 0xd1)]
                }
        }

output :: String
output =
    unlines
        [ "//// GENERATED by offchain/app/GenFreezeVectors.hs. DO NOT EDIT."
        , "//// `just check-freeze-vectors` regenerates and rejects drift."
        , "////"
        , "//// The Haskell encodings of a Freeze spend redeemer, a freeze evidence and"
        , "//// the freeze observer envelope, beside the typed inputs they were built from."
        , ""
        , "use cardano/transaction.{OutputReference}"
        , "use cardano_keri/checkpoint/advance.{AdvanceEvidence}"
        , "use cardano_keri/checkpoint/datum.{KeyMaterial}"
        , "use cardano_keri/checkpoint/observer.{FreezeEvidence}"
        , "use cardano_keri/checkpoint/threshold.{Unweighted}"
        , ""
        , "pub const hunter_output_index: Int = " <> show hunterIndex
        , ""
        , "pub const policy: ByteArray = " <> hex policy
        , ""
        , "pub const spent_ref: OutputReference ="
        , "  OutputReference {"
        , "    transaction_id: " <> hex spentTxId <> ","
        , "    output_index: " <> show spentIndex <> ","
        , "  }"
        , ""
        , "pub const evidence: FreezeEvidence ="
        , "  FreezeEvidence {"
        , "    rotated_keys: KeyMaterial {"
        , "      cur_keys: [" <> hex (BS.replicate 32 0x01) <> "],"
        , "      cur_threshold: Unweighted(1),"
        , "      next_keys: [" <> hex (BS.replicate 32 0x02) <> "],"
        , "      next_threshold: Unweighted(1),"
        , "      witnesses: [" <> hex (BS.replicate 32 0x03) <> "],"
        , "      toad: 1,"
        , "    },"
        , "    rotated_sn: 6,"
        , "    rotation: AdvanceEvidence {"
        , "      event_bytes: " <> hex "rot" <> ","
        , "      off_t: 1,"
        , "      off_i: 2,"
        , "      off_s: 3,"
        , "      off_k: [4],"
        , "      off_kt: 5,"
        , "      off_n: [6],"
        , "      off_nt: 7,"
        , "      off_br: [8],"
        , "      off_ba: [9],"
        , "      off_bt: 10,"
        , "      wit_cut: [" <> hex "cut" <> "],"
        , "      wit_add: [" <> hex "add" <> "],"
        , "      ctrl_sigs: [(0, " <> hex (BS.replicate 64 0xc1) <> ")],"
        , "      wit_receipts: [(1, " <> hex (BS.replicate 64 0xd1) <> ")],"
        , "    },"
        , "  }"
        , ""
        , "pub const spend_redeemer_cbor: ByteArray = " <> hex (cbor (freezeSpendRedeemerData hunterIndex))
        , ""
        , "pub const evidence_cbor: ByteArray = " <> hex (cbor (freezeEvidenceData evidence))
        , ""
        , "pub const observer_envelope_cbor: ByteArray = "
            <> hex (cbor (freezeObserverRedeemerData policy spentTxId spentIndex evidence))
        ]

cbor :: Data -> ByteString
cbor = canonicalCbor . BuiltinData

hex :: ByteString -> String
hex bytes = "#\"" <> BC.unpack (convertToBase Base16 bytes) <> "\""
