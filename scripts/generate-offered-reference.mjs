// Presentation adapter: semantics and example results remain in the spec artifacts.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(repo, 'specs/400-offered-interface');
const out = resolve(process.argv[2] || join(repo, 'docs/offered-api'));
const read = name => readFileSync(join(source, name), 'utf8');
const json = name => JSON.parse(read(name));
const fence = (language, text) => `\n\`\`\`${language}\n${text.trimEnd()}\n\`\`\`\n`;
const example = value => fence('json', JSON.stringify(value, null, 2));
const title = s => s.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, c => c.toUpperCase());
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const head = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: repo, encoding: 'utf8' }).trim();
const gh = `https://github.com/lambdasistemi/cardano-keri/blob/${head}/`;
const cp = json('checkpoint-conformance.json');
const st = json('statements-conformance.json');
const stories = json('operation-stories.json');
const cpProv = json('model-provenance.json');
const stProv = json('statements-provenance.json');
const registry = [...json('refusals.json').refusals, ...json('statements-refusals.json').refusals];
assert.equal(st.source, stProv.sourceCommit);
const cases = [
  ...cp.cells.map(c => ({ operation: `checkpoint.${cp.actions[c.a].action}`,
    name: `state ${c.s}, action ${c.a}, environment ${c.e}`,
    input: { params: cp.params, now: cp.now, state: cp.states[c.s], action: cp.actions[c.a], oracle: cp.envs[c.e] }, result: c.result })),
  ...st.cases.map(c => ({ operation: c.call.action.action, name: c.name,
    input: { params: st.params, ...c.call, oracle: c.oracle }, result: c.result }))
];
const operations = [...new Set(cases.map(c => c.operation))].sort();
assert.deepEqual(Object.keys(stories).sort(), operations, 'story coverage differs from executable corpus');
const families = {
  checkpoint: ['Manage a checkpoint', 'As a controller or advancer, I want to inspect the evidence, state change and addressed value flow for a checkpoint operation.'],
  history: ['Check historical evidence', 'As a relying party, I want to know which historical keys cover a supplied event and whether that range is final or provisional.'],
  mirror: ['Project a revocation mirror', 'As a mirror contributor, I want to open a registry or record a published revocation from its supplied issuer seal.'],
  credential: ['Assess credential chains', 'As a credential holder or relying party, I want to inspect chain admission, cached dependencies and revocation membership.'],
  delegation: ['Use delegated approvals', 'As a delegatee, I want an approval certificate to name my exact event and be consumed by the corresponding model operation.']
};
mkdirSync(join(out, 'sources'), { recursive: true });
const hashes = {};
for (const name of readdirSync(source).sort()) {
  const bytes = readFileSync(join(source, name));
  hashes[name] = sha(bytes);
  // Markdown downloads must not become a second, unrewritten MkDocs page.
  const download = name.endsWith('.md') ? name + '.txt' : name;
  if (name.endsWith('.md')) rmSync(join(out, 'sources', name), { force: true });
  writeFileSync(join(out, 'sources', download), bytes);
}
function page(name, body) {
  writeFileSync(join(out, name + '.md'), '<!-- Generated by scripts/generate-offered-reference.mjs. -->\n' + body);
}
const diagram = `\n\`\`\`mermaid\nflowchart LR\n  Caller[Caller] -->|Supplied published evidence| Assessment[Evidence assessment]\n  Assessment -->|Missing required evidence| Unknown[unknown]\n  Assessment -->|Complete model inputs| Model[Model operation]\n  Model -->|Predicate fails| Refused[Named refusal]\n  Model -->|Predicate holds| Result[State, flow or verdict]\n\`\`\`\n`;
page('index', `# The offered API\n\n## Stories you can explore\n\nAs an SDK author, I want to browse what callers supply, what they obtain and which refusals to handle. This reference is generated from CDDL, the refusal registries and the model conformance corpora.\n\n**Specification candidate.** Preparation is unsigned. Callers supply published evidence; the API has no KERI networking. These are abstract model calls with synthetic fixture oracles, not a deployed transaction or cryptographic codec.\n${diagram}\n${Object.entries(families).map(([f, [t, story]]) => `- [${t}](${f}.md): ${story}`).join('\n')}\n\n## What supports the reference\n\nThe reference covers ${operations.length} operations: eight Checkpoint actions, sixteen statement-model actions and eight queries. Examples come from ${cp.cells.length} checkpoint cells and ${st.cases.length} statement cases. The statement source contains ${Object.keys(stProv.theoremAxioms).length} unproved theorem statements.\n\nRead the [operation catalogue](spec.md), [statement semantics and limits](statements.md), [encoding contract](encoding.md), [implementation gaps](gaps.md) and [CDDL shapes](schemas.md). Model observations do not establish deployment support, proof completion or mirror freshness.\n\n[Source and artifact hashes](provenance.json) bind this generated reference.\n`);
for (const [family, [heading, story]] of Object.entries(families)) {
  let body = `# ${heading}\n\n${story}\n\n${family === 'checkpoint' ? 'Checkpoint is the funded lifecycle profile. Accepted steps return both next state and addressed value flow.' : 'These executable statement-model calls preserve the source boundary. Lifecycle synchronization actions do not bypass Checkpoint funding or evidence guards. The theorem statements remain unproved.'}\n\nExamples below are model fixtures. Their oracle fields describe synthetic verification outcomes; they are not evidence accepted from production callers. The input shown includes common fixture context as well as the call.\n${diagram}\n`;
  for (const operation of operations.filter(o => o.startsWith(family + '.'))) {
    const rows = cases.filter(c => c.operation === operation);
    const refusedNames = [...new Set(rows.flatMap(c => c.result.refusals || (c.result.refusal ? [c.result.refusal] : [])))].sort();
    body += `## ${title(operation.split('.')[1])}\n\nAs a caller, I want to ${stories[operation]}.\n\nOperation: \`${operation}\`. The corpus contains ${rows.length} observations.\n\n`;
    body += refusedNames.length ? `Named refusals:\n\n${refusedNames.map(n => {
      const r = registry.find(r => r.name === n); assert.ok(r, `unregistered ${n}`);
      return `- \`${n}\`: ${r.condition}.`;
    }).join('\n')}\n\n` : 'This query returns a Boolean. False is an evaluated result, not a refusal.\n\n';
    const selected = ['accepted', 'refused'].map(status => rows.find(r => r.result.status === status)).filter(Boolean);
    if (selected.length === 1 && typeof selected[0].result.value === 'boolean') {
      selected.splice(0, 1, ...[true, false].map(value => rows.find(r => r.result.value === value)));
    }
    for (const c of selected) {
      assert.ok(c);
      const label = c.result.status === 'refused' ? 'Refused' : typeof c.result.value === 'boolean' ? `Evaluated ${c.result.value}` : 'Accepted';
      body += `### ${label} example\n\nCaller supplies this model fixture:\n${example(c.input)}\nCaller obtains:\n${example(c.result)}\n`;
    }
  }
  const stem = family === 'checkpoint' ? 'checkpoint' : 'statements';
  body += `\n[Download every example](sources/${stem}-conformance.json) · [Read the complete shape](sources/${stem}-model.cddl) · [Read semantics and limits](${family === 'checkpoint' ? 'spec' : 'statements'}.md)\n`;
  page(family, body);
}
page('schemas', `# Inspect the data shapes\n\nAs an SDK implementer, I want exact named fields and type alternatives alongside the examples. These are the authoritative CDDL files, included verbatim. Maps preserve field names; ordered sequences remain arrays.\n\n\`\`\`mermaid\nflowchart LR\n  Schema[CDDL shapes] -->|Structural validation| Value[Typed model value]\n  Value -->|Source predicates| Result[Model result]\n  Bytes[Original signed evidence bytes] -->|Separate cryptographic profile| Evidence[Verified evidence]\n\`\`\`\n\n## Checkpoint\n${fence('text', read('checkpoint-model.cddl'))}\n## History, mirrors, credentials and delegation\n${fence('text', read('statements-model.cddl'))}\n`);
for (const name of ['spec', 'statements', 'encoding', 'gaps']) {
  const body = read(name + '.md').replace(/\]\(([^)]+)\)/g, (whole, target) => {
    if (/^(https?:|#)/.test(target)) return whole;
    if (target.startsWith('../../')) return `](${gh}${target.slice(6)})`;
    return `](${['spec.md','statements.md','encoding.md','gaps.md'].includes(target) ? target : 'sources/' + target + (target.endsWith('.md') ? '.txt' : '')})`;
  });
  page(name, body);
}
writeFileSync(join(out, 'provenance.json'), JSON.stringify({ specificationCommit: head,
  checkpointSource: cpProv.sourceCommit, statementSource: stProv.sourceCommit, operations,
  sourceHashes: hashes, generatorSha256: sha(readFileSync(fileURLToPath(import.meta.url))) }, null, 2) + '\n');
console.log(JSON.stringify({ output: out, operations: operations.length, checkpointCells: cp.cells.length, statementCases: st.cases.length, pages: 11 }));
