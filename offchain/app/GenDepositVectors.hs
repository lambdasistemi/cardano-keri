{- |
Module      : Main
Description : Haskell-to-Aiken wire parity vectors for the deposit option of Advance (#345)

Generates the committed deposit wire constants from the Haskell encoders in
"Cardano.KERI.AID.Checkpoint.Wire" and "Cardano.KERI.AID.Checkpoint.Deposit".
The Aiken module carries the typed inputs (the bond option's signatures, the
payee output index, a deposit intent) and the CBOR bytes the Haskell encoders
produce for them; the Aiken suite serialises its own typed value and compares,
so a field order, a constructor index or a tuple shape that disagrees between
the layers fails.

Invocation: @gen-deposit-vectors [OUT_PATH]@.  The emitted module is
generated-only and checked for drift by @just check-deposit-vectors@.
-}
module Main (main) where

import Cardano.KERI.AID.Checkpoint.Datum (canonicalCbor)
import Cardano.KERI.AID.Checkpoint.Deposit (
    BondOption (..),
    DepositIntent (..),
    depositDomain,
    depositIntentPreimage,
 )
import Cardano.KERI.AID.Checkpoint.Wire (advanceSpendRedeemerData)
import Data.ByteArray.Encoding (Base (Base16), convertToBase)
import Data.ByteString (ByteString)
import Data.ByteString qualified as BS
import Data.ByteString.Char8 qualified as BC
import PlutusCore.Data (Data)
import PlutusTx.Builtins.Internal (BuiltinData (..))
import System.Environment (getArgs)

main :: IO ()
main = do
    args <- getArgs
    case args of
        [] -> putStr output
        [path] -> writeFile path output
        _ -> error "usage: gen-deposit-vectors [OUT_PATH]"

payeeIndex :: Integer
payeeIndex = 5

-- | The signatures of the deposit option: every field distinct.
signatures :: [(Int, ByteString)]
signatures = [(0, BS.replicate 64 0xc1), (2, BS.replicate 64 0xc2)]

{- | A deposit intent beyond the Lean's rows: every field distinct, a sequence
number past 2^64 and an output index past 23.
-}
intent :: DepositIntent
intent =
    DepositIntent
        { diDomain = depositDomain
        , diNetworkId = 1
        , diCheckpointPolicy = BS.replicate 28 0xc0
        , diSpentTxId = BS.replicate 32 0xe0
        , diSpentIndex = 300
        , diAid = BC.pack "EAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA"
        , diNewSn = 18446744073709551630
        , diNewEpoch = 3
        , diDeposit = 5000000
        }

output :: String
output =
    unlines
        [ "//// GENERATED by offchain/app/GenDepositVectors.hs. DO NOT EDIT."
        , "//// `just check-deposit-vectors` regenerates and rejects drift."
        , "////"
        , "//// The Haskell encodings of the Advance spend redeemer with each bond option"
        , "//// and of a deposit intent, beside the typed inputs they were built from."
        , ""
        , "use cardano/transaction.{OutputReference}"
        , ""
        , "pub const payee_output_index: Int = " <> show payeeIndex
        , ""
        , "pub const signatures: List<(Int, ByteArray)> ="
        , "  [" <> commaSeparated [pair i s | (i, s) <- signatures] <> "]"
        , ""
        , "pub const policy: ByteArray = " <> hex (diCheckpointPolicy intent)
        , ""
        , "pub const spent_ref: OutputReference ="
        , "  OutputReference {"
        , "    transaction_id: " <> hex (diSpentTxId intent) <> ","
        , "    output_index: " <> show (diSpentIndex intent) <> ","
        , "  }"
        , ""
        , "pub const aid: ByteArray = " <> hex (diAid intent)
        , ""
        , "pub const keep_redeemer_cbor: ByteArray = "
            <> hex (cbor (advanceSpendRedeemerData payeeIndex Keep))
        , ""
        , "pub const deposit_redeemer_cbor: ByteArray = "
            <> hex (cbor (advanceSpendRedeemerData payeeIndex (Deposit signatures)))
        , ""
        , "pub const intent_cbor: ByteArray = " <> hex (depositIntentPreimage intent)
        ]
  where
    pair i s = "(" <> show i <> ", " <> hex s <> ")"
    commaSeparated = foldr1 (\a b -> a <> ", " <> b)

cbor :: Data -> ByteString
cbor = canonicalCbor . BuiltinData

hex :: ByteString -> String
hex bytes = "#\"" <> BC.unpack (convertToBase Base16 bytes) <> "\""
