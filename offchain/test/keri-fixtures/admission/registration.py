#!/usr/bin/env python3
"""Stage A/C on the chain: the inception corpus through the Aiken registration predicate.

`gen` writes an Aiken module that builds, for every inception event of the corpus that keripy parses, the
evidence an honest prover would supply (the event bytes, the per-field offsets of gen_fixtures._offsets_record,
the controller signatures and witness receipts the case carried) and the genesis datum an honest prover would
derive from the event, and asks `registration_predicate` for its verdict. Each test prints the verdict name and
fails on purpose: the traces of `aiken check` are the measurement. `compare` joins them with keripy's outcome.

A case whose threshold the datum cannot hold (a nested weight group) or whose bytes keripy refuses at parse has no
evidence an honest prover could build; it is listed with that reason.
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import keripy_admission as K  # noqa: E402
from receipts import verdicts  # noqa: E402
import gen_fixtures as G  # noqa: E402
from keri.core import coring, serdering  # noqa: E402

out = os.environ.get("ADMISSION_OUT") or os.getcwd()
CTX = "DeploymentContext { min_ada: 2000000, d_reg: 1000000000 }"
LOVELACE = 1002000000
ERRORS = ["DRegBelowMinimum", "R3GenesisDatumMismatch", "E1EventTypeMismatch", "E2AidMismatch", "E3SequenceMismatch",
          "E4CurKeysMismatch", "E5CurThresholdMismatch", "E6NextKeysMismatch", "E7NextThresholdMismatch", "E8WitnessesMismatch",
          "E9ToadMismatch", "R7QuorumUnsatisfied", "R7WitnessQuorumUnsatisfied", "R8DepositBelowMinimum"]


def hexof(b):
    return '#"%s"' % b.hex()


def th(t):
    if "count" in t:
        return "Unweighted(%d)" % t["count"]
    if "weighted" in t and all("key" in w for c in t["weighted"] for w in c):
        return "Weighted([%s])" % ", ".join("[" + ", ".join("Weight { num: %d, den: %d }" % tuple(w["key"]) for w in c) + "]" for c in t["weighted"])
    return None


def raw_of(qb64):
    return coring.Matter(qb64=qb64).raw


def cases():
    for c in K.CASES:
        steps = c["build"]()
        st = steps[-1]
        if st["role"] != "subject":
            continue
        sad = K.sad_of(st["raw"])
        if sad["t"] != "icp":
            continue
        yield c, st, sad


def gen(dest):
    keripy = {r["id"]: r for r in json.load(open(os.path.join(out, "keripy-results.json")))["cases"]}
    lines = ["//// the inception corpus through registration_predicate (generated by registration.py; do not edit).",
             "//// Every test prints its verdict and fails on purpose: the traces are the measurement.", "",
             "use cardano_keri/checkpoint/datum.{KeyStateView}",
             "use cardano_keri/checkpoint/registration.{DeploymentContext, RegistrationEvidence, RegistrationInvalid, RegistrationValid, RegistrationVerdict, registration_predicate, R4InceptionInvalid, " + ", ".join(ERRORS) + "}",
             "use cardano_keri/checkpoint/threshold.{Unweighted, Weight, Weighted}", ""]
    lines.append("fn name(v: RegistrationVerdict) -> String {\n  when v is {\n    RegistrationValid -> @\"Valid\"\n    RegistrationInvalid(e) ->\n      when e is {\n" +
                 "".join("        %s -> @\"%s\"\n" % (e, e) for e in ERRORS) + "        R4InceptionInvalid(_) -> @\"R4InceptionInvalid\"\n      }\n  }\n}\n")
    notes = []
    for c, st, sad in cases():
        res = keripy[c["id"]]["steps"][-1]
        if res["outcome"] == "refused-at-parse":
            notes.append({"id": c["id"], "reason": "keripy refuses the bytes at parse: no evidence an honest prover can build"})
            continue
        if not sad["k"]:
            notes.append({"id": c["id"], "reason": "no keys: no datum with a controller quorum can be derived"})
            continue
        cur_t, nxt_t = th(K.threshold_json(sad["kt"])), th(K.threshold_json(sad["nt"]))
        if cur_t is None or nxt_t is None:
            notes.append({"id": c["id"], "reason": "a nested weight group has no representation in the datum's Threshold type"})
            continue
        serder = serdering.SerderKERI(raw=st["raw"])
        off = G._offsets_record(serder)
        sigs = [(t[1], K.sign_with(t, serder.raw).raw) for t in st["sig_by"]]
        wits = [(t[1], K.sign_with(t, serder.raw).raw) for t in st["wit_by"]]
        i = c["id"]
        lines.append("test reg_%s() {\n  let d = KeyStateView {\n    cesr_aid: %s,\n    cur_keys: [%s],\n    cur_threshold: %s,\n    next_keys: [%s],\n    next_threshold: %s,\n    witnesses: [%s],\n    toad: %d,\n    seq: 0,\n    native_sn: 0,\n  }\n"
                     % (i, hexof(raw_of(sad["i"])), ", ".join(hexof(raw_of(k)) for k in sad["k"]), cur_t, ", ".join(hexof(raw_of(k)) for k in sad["n"]), nxt_t,
                        ", ".join(hexof(raw_of(k)) for k in sad.get("b", [])), int(sad["bt"], 16) if isinstance(sad["bt"], str) else sad["bt"]))
        lines.append("  let e = RegistrationEvidence {\n    event_bytes: %s,\n    off_t: %d,\n    off_i: %d,\n    off_s: %d,\n    off_k: %s,\n    off_kt: %d,\n    off_n: %s,\n    off_nt: %d,\n    off_b: %s,\n    off_bt: %d,\n    ctrl_sigs: [%s],\n    wit_receipts: [%s],\n  }\n"
                     % (hexof(serder.raw), off["t"], off["i"], off["s"], off["k"], off["kt"], off["n"], off["nt"], off["b"], off["bt"],
                        ", ".join("(%d, %s)" % (x, hexof(s)) for x, s in sigs), ", ".join("(%d, %s)" % (x, hexof(s)) for x, s in wits)))
        lines.append("  let v = registration_predicate(%s, d, %d, e)\n  trace name(v)\n  False\n}\n" % (CTX, LOVELACE))
    open(dest, "w").write("\n".join(lines) + "\n")
    json.dump(notes, open(os.path.join(out, "registration-not-built.json"), "w"), indent=1)
    print("wrote %s: %d tests, %d cases without evidence" % (dest, sum(1 for l in lines if l.startswith("test ")), len(notes)))


def compare(aiken_txt):
    keripy = {r["id"]: r for r in json.load(open(os.path.join(out, "keripy-results.json")))["cases"]}
    notes = {n["id"]: n["reason"] for n in json.load(open(os.path.join(out, "registration-not-built.json")))}
    expected = [c["id"] for c, st, sad in cases() if c["id"] not in notes]
    verdict = verdicts(aiken_txt, "reg_", expected, ["Valid", "R4InceptionInvalid"] + ERRORS)
    rows = []
    for c, st, sad in cases():
        res = keripy[c["id"]]["steps"][-1]
        k = {"accepted": "accepted", "escrowed": "pending", "refused": "refused", "refused-at-parse": "refused at parse", "unknown": "unknown"}[res["outcome"]]
        if c["id"] in notes:
            rows.append({"case": c["id"], "title": c["title"], "keripy": k, "keripyClass": res["class"], "chain": "no evidence built", "direction": "not comparable: " + notes[c["id"]]})
            continue
        if c["id"] not in verdict:
            raise SystemExit("registration: no named verdict for " + c["id"])
        v = verdict[c["id"]]
        valid = v == "Valid"
        if res["outcome"] == "accepted" and valid:
            d = "agree"
        elif res["outcome"] == "accepted":
            d = "WE-REFUSE"
        elif valid:
            d = "WE-ACCEPT"
        else:
            d = "agree, keripy pends" if res["outcome"] == "escrowed" else "agree"
        rows.append({"case": c["id"], "title": c["title"], "keripy": k, "keripyClass": res["class"], "chain": v, "direction": d})
    json.dump(rows, open(os.path.join(out, "registration-comparison.json"), "w"), indent=1)
    md = ["# Stage A/C on the chain: inceptions through `registration_predicate` (generated; do not edit)\n",
          "| case | what it tests | keripy 1.3.5 | registration predicate | direction |", "|---|---|---|---|---|"]
    for r in rows:
        md.append("| %s | %s | %s | %s | %s |" % (r["case"], r["title"], r["keripy"] + (": " + r["keripyClass"] if r["keripyClass"] else ""), r["chain"], r["direction"]))
    open(os.path.join(out, "REGISTRATION.md"), "w").write("\n".join(md) + "\n")
    for r in rows:
        print(r["case"], "|", r["keripy"], r["keripyClass"][:22], "|", r["chain"], "|", r["direction"][:40])


if __name__ == "__main__":
    gen(sys.argv[2]) if sys.argv[1] == "gen" else compare(sys.argv[2])
