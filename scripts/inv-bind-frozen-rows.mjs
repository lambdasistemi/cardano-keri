#!/usr/bin/env node
// The frozen rows of INV-BIND, as Aiken tests of the structural reader: the 35 grammar rows and the
// 88 top-level string rows, 123 named cases, each on its exact bytes (checked against its recorded SHA-256 here).
//
//   node scripts/inv-bind-frozen-rows.mjs            # write
//   node scripts/inv-bind-frozen-rows.mjs --check    # exit 1 when it drifts
//
// Each test states the row's verdict: accept, or refuse (with the error class the fixture supplies, when it supplies
// one). A positive row that carries anchor items also states the typed projection: the kind and the exact bytes.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const fixtures = join(root, 'offchain/test/keri-fixtures/fixtures');
const files = ['inv_bind_grammar_frozen.json', 'inv_bind_toplevel_strings.json'];
const target = join(root, 'onchain/lib/cardano_keri/checkpoint/inv_bind_frozen_rows_tests.ak');

const kind = { object: 'KindObject', array: 'KindArray', string: 'KindString', number: 'KindNumber', true: 'KindTrue', false: 'KindFalse', null: 'KindNull' };
const name = (id) => 'frozen_' + id.toLowerCase().replace(/[^a-z0-9]+/g, '_');
// a call as `aiken fmt` lays it out: on one line when it fits in 80 columns, else one argument per line
const call = (indent, fn, args) => {
  const line = indent + fn + '(' + args.join(', ') + ')';
  if (line.length <= 80) return line;
  return indent + fn + '(\n' + args.map((a) => indent + '  ' + a + ',').join('\n') + '\n' + indent + ')';
};
const out = [];
const names = [];
const seen = new Set();
let total = 0;
for (const file of files) {
  const rows = JSON.parse(readFileSync(join(fixtures, file), 'utf8')).rows;
  for (const row of rows) {
    if (row.sha256) {
      const digest = createHash('sha256').update(Buffer.from(row.raw_hex, 'hex')).digest('hex');
      if (digest !== row.sha256) throw new Error(row.id + ': the bytes do not match the recorded hash');
    }
    if (seen.has(row.id)) throw new Error('duplicate row ' + row.id);
    seen.add(row.id);
    total += 1;
    const n = name(row.id);
    out.push(`pub const ${n}_bytes: ByteArray =\n  #"${row.raw_hex}"\n`);
    names.push(n);
    const items = row.anchor_items || [];
    if (items.length > 1) throw new Error(row.id + ': the generator states one anchor item per row');
    if (row.expected === 'accept') {
      if (items.length === 1) {
        out.push(`const ${n}_item: ByteArray =\n  #"${Buffer.from(items[0].raw, 'utf8').toString('hex')}"\n`);
        out.push(`test ${n}_accepts() {\n${call('  ', 'accepts_with_anchor', [n + '_bytes', 'reader.' + kind[items[0].kind], n + '_item'])}\n}\n`);
      } else {
        out.push(`test ${n}_accepts() {\n${call('  ', 'accepts_with_no_anchor', [n + '_bytes'])}\n}\n`);
      }
    } else if (row.error) {
      out.push(`test ${n}_refuses() {\n${call('  ', 'refuses_with', [n + '_bytes', 'reader.' + row.error])}\n}\n`);
    } else {
      out.push(`test ${n}_refuses() {\n${call('  ', 'refuses', [n + '_bytes'])}\n}\n`);
    }
  }
}
const header = [
  '//// INV-BIND: the frozen grammar rows (35) and top-level string rows (88), on exact bytes, judged by',
  '//// the structural reader. Generated by scripts/inv-bind-frozen-rows.mjs: do not edit.',
  '',
  'use cardano_keri/checkpoint/event_decoder as reader',
  '',
  'fn accepts_with_anchor(',
  '  raw: ByteArray,',
  '  kind: reader.AnchorKind,',
  '  item: ByteArray,',
  ') -> Bool {',
  '  when reader.decode_establishment_event(raw) is {',
  '    reader.DecodeOk(event) ->',
  '      event.anchor == [reader.AnchorItem { kind, bytes: item }]',
  '    reader.DecodeErr(_) -> False',
  '  }',
  '}',
  '',
  'fn accepts_with_no_anchor(raw: ByteArray) -> Bool {',
  '  when reader.decode_establishment_event(raw) is {',
  '    reader.DecodeOk(_) -> True',
  '    reader.DecodeErr(_) -> False',
  '  }',
  '}',
  '',
  'fn refuses(raw: ByteArray) -> Bool {',
  '  when reader.decode_establishment_event(raw) is {',
  '    reader.DecodeOk(_) -> False',
  '    reader.DecodeErr(_) -> True',
  '  }',
  '}',
  '',
  'fn refuses_with(raw: ByteArray, want: reader.EventDecodeError) -> Bool {',
  '  when reader.decode_establishment_event(raw) is {',
  '    reader.DecodeErr(e) -> e == want',
  '    reader.DecodeOk(_) -> False',
  '  }',
  '}',
  '',
].join('\n');
const text = header + '\n' + out.join('\n') + `// ${total} named cases\n`;
if (total !== 123) throw new Error('expected 123 named cases, found ' + total);
const baseRow = JSON.parse(readFileSync(join(fixtures, files[0]), 'utf8')).rows.find((r) => r.id === 'OBJ-1');
const base = JSON.parse(Buffer.from(baseRow.raw_hex, 'hex').toString('utf8'));
const rawOf = (text) => Buffer.from('A' + text.slice(1), 'base64url').subarray(1).toString('hex');
const hexOfText = (text) => Buffer.from(text, 'utf8').toString('hex');
const lst = (xs, f, indent) => {
  const items = xs.map(f);
  const one = '[' + items.join(', ') + ']';
  if (indent.length + one.length + 12 <= 80) return one;
  return '[\n' + items.map((i) => indent + '  ' + i + ',').join('\n') + '\n' + indent + ']';
};
if (base.kt !== '2' || base.nt !== '2' || base.bt !== '0' || base.b.length !== 0) throw new Error('unexpected base event');
const binderTarget = join(root, 'onchain/lib/cardano_keri/checkpoint/inv_bind_frozen_binders_tests.ak');
const binderHeader = [
  '//// INV-BIND: the same 123 rows bound by the registration binder against the datum of the base event,',
  '//// by the production binding (the canonical event rebuilt from the datum and compared whole) and the reference reading (the',
  '//// structural reader field by field, tests only). Each row has a test that the two agree and one cost test each.',
  '//// Generated by scripts/inv-bind-frozen-rows.mjs: do not edit.',
  '',
  'use cardano_keri/checkpoint/binding_reference.{InceptionBound, inception_axis}',
  'use cardano_keri/checkpoint/datum.{KeyStateView}',
  'use cardano_keri/checkpoint/inv_bind_frozen_rows_tests as rows',
  'use cardano_keri/checkpoint/registration.{',
  '  QualifiedSpelling, RegistrationEvidence, RegistrationValid, event_binding,',
  '}',
  'use cardano_keri/checkpoint/registration_vectors as vec',
  'use cardano_keri/checkpoint/threshold.{Unweighted}',
  '',
  'pub const base_aid: ByteArray =',
  '  #"' + hexOfText(base.i) + '"',
  '',
  'const base_keys: List<ByteArray> =',
  '  ' + lst(base.k, (k) => '#"' + hexOfText(k) + '"', '  '),
  '',
  'pub fn base_datum() -> KeyStateView {',
  '  KeyStateView {',
  '    cesr_aid: #"' + rawOf(base.i) + '",',
  '    cur_keys: ' + lst(base.k, (k) => '#"' + rawOf(k) + '"', '    ') + ',',
  '    cur_threshold: Unweighted(2),',
  '    next_keys: ' + lst(base.n, (k) => '#"' + rawOf(k) + '"', '    ') + ',',
  '    next_threshold: Unweighted(2),',
  '    witnesses: [],',
  '    toad: 0,',
  '    seq: 0,',
  '    native_sn: 0,',
  '  }',
  '}',
  '',
  'pub fn spelling() -> QualifiedSpelling {',
  '  QualifiedSpelling { aid: base_aid, cur_keys: base_keys }',
  '}',
  '',
  'pub fn evidence(bytes: ByteArray) -> RegistrationEvidence {',
  '  RegistrationEvidence { ..vec.pos_2key_evidence, event_bytes: bytes }',
  '}',
  '',
  'fn reference_valid(bytes: ByteArray) -> Bool {',
  '  inception_axis(base_datum(), spelling(), bytes) == InceptionBound',
  '}',
  '',
  'fn agree(bytes: ByteArray) -> Bool {',
  '  reference_valid(bytes) == production_valid(bytes)',
  '}',
  '',
  'fn production_valid(bytes: ByteArray) -> Bool {',
  '  event_binding(base_datum(), spelling(), evidence(bytes)) == RegistrationValid',
  '}',
  '',
].join('\n');
const binderTests = names.map((n) => [
  `test ${n}_binding_agrees_with_reference() {`,
  `  agree(rows.${n}_bytes)`,
  '}',
  '',
  `test ${n}_cost_reference() {`,
  `  reference_valid(rows.${n}_bytes) || True`,
  '}',
  '',
  `test ${n}_cost_production() {`,
  `  production_valid(rows.${n}_bytes) || True`,
  '}',
  '',
].join('\n'));
const binderText = binderHeader + '\n' + binderTests.join('\n') + `// ${total} named cases\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(binderTarget, 'utf8') !== binderText) {
    console.error('the frozen binder rows drift from their generator');
    process.exit(1);
  }
} else {
  writeFileSync(binderTarget, binderText);
}
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) {
    console.error('the frozen rows drift from their generator');
    process.exit(1);
  }
  console.log('the frozen rows match their generator (' + total + ' cases)');
} else {
  writeFileSync(target, text);
  console.log('wrote ' + total + ' cases to ' + target);
}
