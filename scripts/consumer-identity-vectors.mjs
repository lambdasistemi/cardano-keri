#!/usr/bin/env node
// Generates onchain/lib/cardano_keri/consumer_identity_vectors.ak from
// lean/consumer-identity-vectors.json (the vectors the Lean concrete
// interpretation `CardanoKeri.ConsumerIdentity.Bytes` produces).
//
//   node scripts/consumer-identity-vectors.mjs            # write the module
//   node scripts/consumer-identity-vectors.mjs --check    # exit 1 when the module drifts
//
// The mapping of the Lean values onto Aiken values is written here, once, and
// restated in the header of the generated module:
//   statePreimage, stateName, key, activePreimage, activeName, asset
//                                      -> byte strings, as in the file
//   statePolicy                        -> byte string
//   seed                               -> OutputReference
//   aid (qualified CESR text)          -> the Lean `aidOfCesr`: the bijective
//                                         base-256 numeral of its UTF-8 bytes
//                                         (least significant digit first)
// The numeral is computed here, independently of the Aiken `pack`, so the
// generated vectors check the Aiken side in both directions.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inPath = resolve(root, 'lean/consumer-identity-vectors.json');
const outPath = resolve(root, 'onchain/lib/cardano_keri/consumer_identity_vectors.ak');

const isHex = (s, bytes) => typeof s === 'string' && /^([0-9a-f]{2})*$/.test(s) && (bytes === undefined || s.length === 2 * bytes);

// Lean `pack`: b0 + 1 + 256 * pack(rest); the empty string is 0.
const pack = (bs) => bs.reduceRight((acc, b) => BigInt(b) + 1n + 256n * acc, 0n);
const utf8 = (s) => [...Buffer.from(s, 'utf8')];

const data = JSON.parse(readFileSync(inPath, 'utf8'));
const expectedLayout = ['statePreimage', 'name', 'key', 'asset', 'activePreimage'];
if (JSON.stringify(Object.keys(data.layout)) !== JSON.stringify(expectedLayout)) throw new Error('layout object changed');
if (!Array.isArray(data.vectors) || data.vectors.length !== 8) throw new Error(`expected 8 vectors, found ${data.vectors && data.vectors.length}`);

const ident = (id) => {
  const name = id.replace(/-/g, '_');
  if (!/^[a-z][a-z0-9_]*$/.test(name)) throw new Error(`vector id is not an identifier: ${id}`);
  return name;
};

const vectorFn = (v) => {
  const id = ident(v.id);
  if (!isHex(v.input.statePolicy, 28)) throw new Error(`${v.id}: state policy`);
  if (!isHex(v.input.seed.transactionId, 32)) throw new Error(`${v.id}: seed transaction id`);
  if (!Number.isSafeInteger(v.input.seed.outputIndex) || v.input.seed.outputIndex < 0) throw new Error(`${v.id}: seed output index`);
  for (const f of ['statePreimage', 'activePreimage', 'key']) if (!isHex(v[f])) throw new Error(`${v.id}: ${f}`);
  for (const f of ['stateName', 'activeName']) if (!isHex(v[f], 32)) throw new Error(`${v.id}: ${f}`);
  // The vector's own consistency, independent of any implementation.
  const key = Buffer.from(utf8(v.input.aid)).toString('hex');
  if (v.key !== key) throw new Error(`${v.id}: key is not the UTF-8 bytes of the CESR text`);
  if (v.asset.policy !== v.input.statePolicy) throw new Error(`${v.id}: asset policy is not the state policy`);
  if (v.asset.name !== v.activeName) throw new Error(`${v.id}: asset name is not the active name`);
  const aid = pack(utf8(v.input.aid));
  return {
    id,
    text: `/// Vector \`${v.id}\`: ${v.note}.
pub fn vector_${id}() -> IdentityVector {
  IdentityVector {
    state_policy: #"${v.input.statePolicy}",
    seed: OutputReference {
      transaction_id: #"${v.input.seed.transactionId}",
      output_index: ${v.input.seed.outputIndex},
    },
    aid: ${aid},
    state_preimage: #"${v.statePreimage}",
    state_name: #"${v.stateName}",
    key: #"${v.key}",
    active_preimage: #"${v.activePreimage}",
    active_name: #"${v.activeName}",
    asset: Token {
      policy: #"${v.asset.policy}",
      name: #"${v.asset.name}",
    },
  }
}
`,
  };
};

const fields = [
  ['state_preimage', 'state_preimage_ok'],
  ['state_name', 'state_name_ok'],
  ['key', 'key_ok'],
  ['aid', 'aid_ok'],
  ['active_preimage', 'active_preimage_ok'],
  ['active_name', 'active_name_ok'],
  ['asset', 'asset_ok'],
];

const header = `//// GENERATED by scripts/consumer-identity-vectors.mjs from
//// lean/consumer-identity-vectors.json. DO NOT EDIT.
//// \`just check-consumer-identity-vectors\` regenerates and rejects drift.
////
//// One function per vector, and for each vector one test per claim of the
//// Lean concrete interpretation: the state preimage, the registry name, the
//// key in both directions, the active preimage, the active name and the
//// representative asset. The expected bytes are the Lean's, written out; the
//// Aiken concrete interpretation is the thing under test.
////
//// Mapping of the Lean values onto Aiken values (written once, in the
//// generator):
////   preimages, names, key, policy    byte strings, as in the JSON
////   seed                             OutputReference
////   aid                              the Lean aidOfCesr of the qualified CESR
////                                    text: the bijective base-256 numeral of
////                                    its UTF-8 bytes, computed by the generator
`;

const vs = data.vectors.map(vectorFn);
let body = '';
for (const v of vs) body += `\n${v.text}`;
body += `\n/// Every vector, in file order.\npub fn vectors() -> List<IdentityVector> {\n  [\n${vs.map((v) => `    vector_${v.id}(),\n`).join('')}  ]\n}\n`;
for (const v of vs) {
  for (const [name, check] of fields) {
    body += `\ntest ${v.id}_${name}() {\n  ${check}(vector_${v.id}())\n}\n`;
  }
}

const WIDTH = 80;
// import list wrapped the way `aiken fmt` keeps it
const importBlock = (module, names) => {
  const one = `use ${module}.{${names.join(', ')}}`;
  if (one.length <= WIDTH) return one;
  const lines = [];
  let cur = '  ';
  for (const n of names) {
    const piece = (cur.trim() ? ' ' : '') + n + ',';
    if ((cur + piece).length > WIDTH) { lines.push(cur); cur = '  ' + n + ','; } else cur += piece;
  }
  lines.push(cur);
  return `use ${module}.{\n${lines.join('\n')}\n}`;
};
const imports = `
use cardano/transaction.{OutputReference}
use cardano_keri/consumer.{Token}
${importBlock('cardano_keri/consumer_identity_check', ['IdentityVector', ...fields.map(([, c]) => c)].sort())}
`;

const text = header + imports + body;
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(outPath, 'utf8'); } catch { /* absent */ }
  if (current !== text) {
    console.error('consumer identity vectors drifted from lean/consumer-identity-vectors.json; run: node scripts/consumer-identity-vectors.mjs');
    process.exit(1);
  }
  console.log(`consumer identity vectors current (${vs.length} vectors, ${vs.length * fields.length} generated tests)`);
} else {
  writeFileSync(outPath, text);
  console.log(`wrote ${outPath} (${vs.length} vectors, ${vs.length * fields.length} generated tests)`);
}
