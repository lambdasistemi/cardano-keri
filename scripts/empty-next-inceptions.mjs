#!/usr/bin/env node
// Three signed inceptions whose next declaration is empty (`n` empty, `nt` zero): a non-transferable key identifier
// (`B`), a transferable key identifier (`D`), and a transferable key identifier with one seal in its anchor. The seeds
// are fixed, so the bytes are reproducible. Writes onchain/lib/cardano_keri/checkpoint/empty_next_bytes.ak;
// `--check` fails on drift. Needs `b3sum` on the path (blake3 of the dressed event).
import { createHash, createPrivateKey, createPublicKey, sign } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'onchain/lib/cardano_keri/checkpoint/empty_next_bytes.ak');
const dress = '#'.repeat(44);
const qualify = (code, raw) => code + Buffer.concat([Buffer.from([0]), raw]).toString('base64url').slice(1);
const blake3 = (text) => Buffer.from(execFileSync('b3sum', ['--no-names'], { input: Buffer.from(text, 'latin1') }).toString().trim(), 'hex');
const hex6 = (n) => n.toString(16).padStart(6, '0');
const digestOf = (label) => qualify('E', createHash('sha256').update(label).digest());

const cases = [
  { name: 'b_empty', code: 'B', anchor: '[]' },
  { name: 'd_empty', code: 'D', anchor: '[]' },
  { name: 'd_seal', code: 'D', anchor: `[{"i":"${digestOf('seal-i')}","s":"0","d":"${digestOf('seal-d')}"}]` },
];

const lines = [
  '//// Generated by scripts/empty-next-inceptions.mjs: do not edit.',
  '////',
  '//// Three signed inceptions whose next declaration is empty (`n` empty, `nt` zero): a non-transferable key',
  '//// identifier, a transferable key identifier, and a transferable key identifier with one seal in its anchor.',
  '',
];
for (const c of cases) {
  const seed = createHash('sha256').update('empty-next-' + c.name).digest();
  const priv = createPrivateKey({ key: Buffer.concat([Buffer.from('302e020100300506032b657004220420', 'hex'), seed]), format: 'der', type: 'pkcs8' });
  const raw = createPublicKey(priv).export({ format: 'der', type: 'spki' }).subarray(-32);
  const identifier = qualify(c.code, raw);
  const body = (v, d) => `{"v":"KERI10JSON${v}_","t":"icp","d":"${d}","i":"${identifier}","s":"0","kt":"1","k":["${identifier}"],"nt":"0","n":[],"bt":"0","b":[],"c":[],"a":${c.anchor}}`;
  const size = body('000000', dress).length;
  const digest = qualify('E', blake3(body(hex6(size), dress)));
  const event = body(hex6(size), digest);
  const signature = sign(null, Buffer.from(event, 'latin1'), priv);
  const hexOf = (b) => Buffer.from(b).toString('hex');
  lines.push(`pub const ${c.name}_event: ByteArray =\n  #"${hexOf(Buffer.from(event, 'latin1'))}"\n`);
  lines.push(`pub const ${c.name}_signature: ByteArray =\n  #"${hexOf(signature)}"\n`);
  lines.push(`pub const ${c.name}_key: ByteArray =\n  #"${hexOf(raw)}"\n`);
  lines.push(`pub const ${c.name}_identifier: ByteArray =\n  #"${hexOf(Buffer.from(identifier, 'latin1'))}"\n`);
}
const text = lines.join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) { console.error('the empty-next inceptions drift from their generator'); process.exit(1); }
  console.log('the empty-next inceptions match their generator');
} else {
  writeFileSync(target, text);
  console.log('wrote ' + target);
}
