{- |
Module      : Main
Description : Haskell-to-Aiken wire parity vectors for the bounded top-up (#522)

Generates the committed top-up wire constants from the Haskell encoders in
"Cardano.KERI.AID.Checkpoint.Wire" and "Cardano.KERI.AID.Checkpoint.Datum". The
Aiken module carries both the typed inputs (an amount, a live datum with the
top-up mark clear and the same datum with it set) and the CBOR bytes the
Haskell encoders produce for them; the Aiken suite serialises its own typed
value and compares, so a constructor index, a field order or a Boolean shape
that disagrees between the layers fails.

Invocation: @gen-topup-vectors [OUT_PATH]@.  The emitted module is
generated-only and checked for drift by @just check-topup-vectors@.
-}
module Main (main) where

import Cardano.KERI.AID.Checkpoint.Datum (
    CheckpointDatum (..),
    CheckpointDatumV2 (..),
    KeyMaterial (..),
    canonicalCbor,
 )
import Cardano.KERI.AID.Checkpoint.Threshold (Threshold (..))
import Cardano.KERI.AID.Checkpoint.Wire (topUpSpendRedeemerData)
import Data.ByteArray.Encoding (Base (Base16), convertToBase)
import Data.ByteString (ByteString)
import Data.ByteString qualified as BS
import Data.ByteString.Char8 qualified as BC
import PlutusCore.Data (Data)
import PlutusTx.Builtins.Internal (BuiltinData (..))
import System.Environment (getArgs)

main :: IO ()
main = do
    args <- getArgs
    case args of
        [] -> putStr output
        [path] -> writeFile path output
        _ -> error "usage: gen-topup-vectors [OUT_PATH]"

amount :: Integer
amount = 3_500_000

aidText, refundTo :: ByteString
aidText = BC.pack "EMMcQtoqOkACLvyswJTFXUQmRbZhWt4ALjjhXzLGhr5P"
refundTo = BS.cons 0x61 (BS.replicate 28 0x53)

-- | A live checkpoint, every field distinct, with the top-up mark given.
live :: Bool -> CheckpointDatumV2
live toppedUp =
    Live
        { lvAid = aidText
        , lvSn = 4
        , lvEpoch = 2
        , lvPoisoned = True
        , lvFrozen = False
        , lvBornAt = 100
        , lvRefundTo = refundTo
        , lvToppedUp = toppedUp
        , lvKeys =
            KeyMaterial
                { kmCurKeys = [BS.replicate 32 0x01]
                , kmCurThreshold = Unweighted 1
                , kmNextKeys = [BS.replicate 32 0x02]
                , kmNextThreshold = Unweighted 1
                , kmWitnesses = [BS.replicate 32 0x03]
                , kmToad = 1
                }
        }

liveText :: String -> Bool -> [String]
liveText name toppedUp =
    [ "pub const " <> name <> ": CheckpointDatumV2 ="
    , "  Live {"
    , "    aid: " <> hex aidText <> ","
    , "    sn: 4,"
    , "    epoch: 2,"
    , "    poisoned: True,"
    , "    frozen: False,"
    , "    born_at: 100,"
    , "    refund_to: " <> hex refundTo <> ","
    , "    topped_up: " <> (if toppedUp then "True" else "False") <> ","
    , "    keys: KeyMaterial {"
    , "      cur_keys: [" <> hex (BS.replicate 32 0x01) <> "],"
    , "      cur_threshold: Unweighted(1),"
    , "      next_keys: [" <> hex (BS.replicate 32 0x02) <> "],"
    , "      next_threshold: Unweighted(1),"
    , "      witnesses: [" <> hex (BS.replicate 32 0x03) <> "],"
    , "      toad: 1,"
    , "    },"
    , "  }"
    ]

output :: String
output =
    unlines $
        [ "//// GENERATED by offchain/app/GenTopUpVectors.hs. DO NOT EDIT."
        , "//// `just check-topup-vectors` regenerates and rejects drift."
        , "////"
        , "//// The Haskell encodings of a TopUp spend redeemer and of a live checkpoint"
        , "//// datum with the top-up mark clear and set, beside the typed inputs they"
        , "//// were built from."
        , ""
        , "use cardano_keri/checkpoint/datum.{CheckpointDatumV2, KeyMaterial, Live}"
        , "use cardano_keri/checkpoint/threshold.{Unweighted}"
        , ""
        , "pub const amount: Int = " <> show amount
        , ""
        ]
            <> liveText "live_clear" False
            <> [""]
            <> liveText "live_marked" True
            <> [ ""
               , "pub const spend_redeemer_cbor: ByteArray = " <> hex (cbor (topUpSpendRedeemerData amount))
               , ""
               , "pub const live_clear_cbor: ByteArray = " <> hex (canonicalCbor (V2 (live False)))
               , ""
               , "pub const live_marked_cbor: ByteArray = " <> hex (canonicalCbor (V2 (live True)))
               ]

cbor :: Data -> ByteString
cbor = canonicalCbor . BuiltinData

hex :: ByteString -> String
hex bytes = "#\"" <> BC.unpack (convertToBase Base16 bytes) <> "\""
