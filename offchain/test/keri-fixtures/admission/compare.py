#!/usr/bin/env python3
"""Join keripy-results.json with the Lean driver's output (lean-output.jsonl) into COMPARISON.md and comparison.json.

A row is compared only with the layer that models the same admission stage; everything else is
listed as not comparable with the reason. Direction vocabulary:
  agree                       same admission verdict (both admit, or neither admits)
  agree, keripy pends         neither admits; keripy keeps the event as pending evidence (escrow), the model refuses outright
  WE-ACCEPT                   the model admits what keripy does not (accepts into the log)
  WE-REFUSE                   the model refuses what keripy admits
  not comparable              no like stage on the model side
"""
import json, os

HERE = os.environ.get("ADMISSION_OUT") or os.getcwd()
res = json.load(open(os.path.join(HERE, "keripy-results.json")))

def die(msg):
    raise SystemExit("compare: " + msg)


subjects = [(c["id"], st["role"]) for c in res["cases"] for st in c["steps"] if st["role"] == "subject"]
if len(subjects) != len(set(subjects)):
    die("keripy results repeat a subject step")
inputs = {}
for r in json.load(open(os.path.join(HERE, "lean-input.json")))["rows"]:
    key = (r["case"], r["role"])
    if key in inputs:
        die("the translation repeats a row for %s" % (key,))
    inputs[key] = r
if set(inputs) != set(subjects):
    die("translated rows differ from the subject steps: missing %s, unexpected %s" % (sorted(set(subjects) - set(inputs)), sorted(set(inputs) - set(subjects))))
lean = {}
for line in open(os.path.join(HERE, "lean-output.jsonl")):
    r = json.loads(line)
    key = (r["case"], r["role"])
    if key in lean:
        die("more than one model result for %s" % (key,))
    if "untranslatable" in r:
        die("the model driver could not read %s: %s" % (key, r["untranslatable"]))
    lean[key] = r
if set(lean) != set(inputs):
    die("model results differ from the translated rows: missing %s, unexpected %s" % (sorted(set(inputs) - set(lean)), sorted(set(lean) - set(inputs))))
for key, r in lean.items():
    if inputs[key]["comparable"] and not isinstance(r.get("rotationValid"), bool):
        die("model result for %s has no rotationValid" % (key,))
    if not inputs[key]["comparable"] and "notComparable" not in r:
        die("model result for %s answers a row declared not comparable" % (key,))

KCLS = {"accepted": "accepted", "escrowed": "pending", "refused": "refused", "refused-at-parse": "refused at parse", "unknown": "unknown"}


def admission(out, valid):
    if out == "accepted" and valid:
        return "agree"
    if out == "accepted":
        return "WE-REFUSE"
    if valid:
        return "WE-ACCEPT"
    return "agree, keripy pends" if out == "escrowed" else "agree"


rows = []
for c in res["cases"]:
    for st in c["steps"]:
        if st["role"] != "subject":
            continue
        m = lean[(c["id"], st["role"])]
        base = {"case": c["id"], "stage": c["stage"], "family": c["family"], "title": c["title"], "ilk": st["ilk"], "sn": st["sn"],
                "said": st["said"], "pre": st["pre"], "raw": st["raw"]}
        if "notComparable" in m:
            rows.append({**base, "role": st["role"], "keripy": KCLS[st["outcome"]], "keripyClass": st["class"], "keripyDetail": st["detail"],
                         "model": "no like surface", "direction": "not comparable: " + m.get("notComparable", "no model row")})
        else:
            rows.append({**base, "role": st["role"], "keripy": KCLS[st["outcome"]], "keripyClass": st["class"], "keripyDetail": st["detail"],
                         "model": "valid" if m["rotationValid"] else "invalid", "direction": admission(st["outcome"], m["rotationValid"])})

json.dump(rows, open(os.path.join(HERE, "comparison.json"), "w"), indent=1)
md = ["# Comparison, generated by compare.py (do not edit)\n",
      "| case | stage | role | input (ilk, sn, SAID, prefix) | what it tests | keripy 1.3.5 | model | direction |", "|---|---|---|---|---|---|---|---|"]
for r in rows:
    said = (r["said"] or "")[:12] + "…" if r["said"] else "-"
    pre = (r["pre"] or "")[:12] + "…" if r["pre"] else "-"
    k = r["keripy"] + ((": " + r["keripyClass"]) if r["keripyClass"] else "")
    md.append("| %s | %s | %s | %s, sn %s, `%s`, `%s` | %s | %s | %s | %s |" % (
        r["case"], r["stage"], r["role"], r["ilk"], r["sn"], said, pre, r["title"], k, r["model"], r["direction"]))
open(os.path.join(HERE, "COMPARISON.md"), "w").write("\n".join(md) + "\n")
tally = {}
for r in rows:
    key = r["direction"].split(":")[0]
    tally[key] = tally.get(key, 0) + 1
print(json.dumps(tally, indent=1))
for r in rows:
    if r["direction"] in ("WE-ACCEPT", "WE-REFUSE", "review"):
        print(r["case"], r["role"], r["direction"][:28], "|", r["keripy"], r["keripyClass"], "|", r["model"], "|", r["title"][:60])
