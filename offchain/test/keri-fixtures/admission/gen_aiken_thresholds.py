#!/usr/bin/env python3
"""Write the Aiken module that puts every thresholds.json case to the on-chain codec.

For each case that the codec's type can hold (a flat or clause-partitioned list of num/den weights, or an
integer) the module has one test `wf_<id>` (the codec calls the threshold well formed over distinct 32-byte
keys) and one test `ev_<id>_<signers>` per signer subset (`evaluate` returns true). A test that fails is a
`false` answer of the codec: the run is the measurement, and its pass/fail list is read by
compare_thresholds.py. Nested weight groups have no representation in the codec's `Weight` type and are
listed as such, not skipped silently.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from receipts import representable, subset_label  # noqa: E402

out = os.environ.get("ADMISSION_OUT") or os.getcwd()
dest = sys.argv[1]
data = json.load(open(os.path.join(out, "thresholds.json")))


def aiken_threshold(th):
    if "count" in th:
        return "Unweighted(%d)" % th["count"]
    clauses = ", ".join("[" + ", ".join("Weight { num: %d, den: %d }" % tuple(w["key"]) for w in clause) + "]"
                        for clause in th["weighted"])
    return "Weighted([%s])" % clauses


def key(i):
    return '#"' + ("%02x" % (i + 1)) * 32 + '"'


lines = ["//// Stage B: the codec's verdicts on the corpus of thresholds.json (generated by gen_aiken_thresholds.py; do not edit).",
         "//// A failing test is a `false` answer of the codec, not a defect by itself: compare_thresholds.py reads the list.", "",
         "use cardano_keri/checkpoint/threshold.{Unweighted, Valid, Weight, Weighted, evaluate, well_formed}", ""]
for c in data["cases"]:
    th = c["threshold"]
    if not representable(th):
        lines.append("// %s: not representable in the codec's Weight type (%s)" % (c["id"], "nested weight group or unparsed form"))
        continue
    t = aiken_threshold(th)
    keys = ", ".join(key(i) for i in range(c["n"]))
    lines.append("test wf_%s() {\n  well_formed([%s], %s) == Valid\n}\n" % (c["id"], keys, t))
    for r in range(2 ** c["n"]):
        who = [i for i in range(c["n"]) if (r >> i) & 1]
        label = subset_label(who)
        lines.append("test ev_%s_%s() {\n  evaluate(%s, %d, [%s])\n}\n" % (c["id"], label, t, c["n"], ", ".join(map(str, who))))
open(dest, "w").write("\n".join(lines) + "\n")
print("wrote", dest, sum(1 for l in lines if l.startswith("test ")), "tests")
