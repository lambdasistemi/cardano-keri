#!/usr/bin/env node
// The three signed inceptions of the local chain run whose booking the attestation refused (B empty, D empty, D seal),
// kept as the CESR exports the run produced: the signed body and its indexed controller signature attachment, byte for
// byte. Checks each export against its recorded SHA-256, splits the body at the length its version string declares,
// checks the attachment is one indexed controller signature, checks that signature over the body with the key the
// body names, and writes onchain/lib/cardano_keri/checkpoint/link2_exports.ak. `--check` fails on drift.
import { createHash, createPublicKey, verify } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'offchain/test/keri-fixtures/fixtures/link2');
const target = join(root, 'onchain/lib/cardano_keri/checkpoint/link2_exports.ak');
const names = ['b-empty', 'd-empty', 'd-seal'];
const sums = Object.fromEntries(readFileSync(join(dir, 'SHA256SUMS'), 'utf8').trim().split('\n').map((l) => { const [h, f] = l.split(/\s+/); return [f, h]; }));
const rawOf = (text) => Buffer.from('A' + text.slice(1), 'base64url').subarray(1);

const lines = [
  '//// Generated by scripts/link2-exports.mjs: do not edit.',
  '////',
  '//// The three signed inceptions of the local chain run whose booking was refused, as exported: the signed body and',
  '//// its indexed controller signature attachment (`-VAX-AAB` and one 88 character signature), byte for byte, with',
  '//// the SHA-256 of each export and the length of its body.',
  '',
];
for (const name of names) {
  const file = name + '.cesr';
  const export_ = readFileSync(join(dir, file));
  const sha = createHash('sha256').update(export_).digest('hex');
  if (sums[file] !== sha) throw new Error(file + ': SHA-256 differs from the recorded one');
  const size = parseInt(/^\{"v":"KERI10JSON([0-9a-f]{6})_"/.exec(export_.toString('latin1'))[1], 16);
  const body = export_.subarray(0, size);
  const attachment = export_.subarray(size).toString('latin1');
  if (!/^-VAX-AAB[A-Za-z0-9_-]{88}$/.test(attachment)) throw new Error(file + ': the attachment is not one indexed controller signature');
  if (body[size - 1] !== 0x7d) throw new Error(file + ': the body does not end at its declared size');
  const event = JSON.parse(body.toString('latin1'));
  if (event.t !== 'icp' || event.k.length !== 1 || event.k[0] !== event.i || event.n.length !== 0 || event.nt !== '0') throw new Error(file + ': not an empty-next inception');
  const signature = Buffer.from('AA' + attachment.slice(8 + 2), 'base64url').subarray(2);
  if (attachment.slice(8, 10) !== 'AA' || signature.length !== 64) throw new Error(file + ': unexpected signature code');
  const spki = Buffer.concat([Buffer.from('302a300506032b6570032100', 'hex'), rawOf(event.i)]);
  if (!verify(null, body, createPublicKey({ key: spki, format: 'der', type: 'spki' }), signature)) throw new Error(file + ': the signature does not verify');
  const id = name.replace('-', '_');
  lines.push(`pub const ${id}_export: ByteArray =\n  #"${export_.toString('hex')}"\n`);
  lines.push(`pub const ${id}_export_sha256: ByteArray =\n  #"${sha}"\n`);
  lines.push(`pub const ${id}_body_size: Int = ${size}\n`);
}
const text = lines.join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) { console.error('the link 2 exports drift from their generator'); process.exit(1); }
  console.log('the link 2 exports match their generator');
} else {
  writeFileSync(target, text);
  console.log('wrote ' + target);
}
